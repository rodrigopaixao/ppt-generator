/** Integration: configure native content and PptxGenJS additions in a single PPTX. */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { build, parseArguments } from '../src/generate.mjs';

test('native configuration edits text, table, chart and imports PptxGenJS additions', async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'native-integration-'));
  try {
    const result = await build({ selection: [5, 10, 38, 50, 68],
      elements: {
        '5.e5': { text: 'Configured executive summary', textStyle: { fontSize: 18 } },
        '38.e6': { image: 'assets/source-50-geometry-4.svg' },
      },
      slides: {
        10: { elements: { e8: { table: { cells: { '1.2': { text: 'Configured transfer' } } } } } },
        68: { hidden: false, elements: { e114: { chart: { series: [{ values: [2, 7, 2, 11] }] } } } },
      },
      additions: { 50: [{ id: 'annotation', kind: 'text', text: 'Generated by PptxGenJS',
        grid: { col: 1, row: 8, colSpan: 10, rowSpan: 0.5 },
        style: { fontSize: 8, color: 'EC111A' } }] },
    }, { output: path.join(directory, 'configured.pptx') });
    assert.equal(result.manifest.length, 5);
    assert.equal(result.report.baselineVisualPartsByteIdentical, false);
    assert.equal(result.report.counts.additions, 1);
    assert.equal(result.manifest[0].elements.find(e => e.id === 'e5').text, 'Configured executive summary');
    assert(result.manifest[1].elements.find(e => e.id === 'e8').cells[1][2].includes('Configured transfer'));
    assert(result.manifest.find(s => s.sourceNumber === 50).elements.some(e => e.name === 'custom.annotation'));
    assert(result.report.changedParts.includes('ppt/charts/config-s68-e114.xml'));
    assert(result.report.changedParts.includes('ppt/media/config-s38-e6.svg'));
    assert(result.report.changedParts.includes('ppt/media/config-s38-e6.png'));
  } finally { fs.rmSync(directory, { recursive: true, force: true }); }
});

test('CLI rejects unknown modes/options instead of silently ignoring settings', () => {
  assert.throws(() => parseArguments(['--mode', 'unknown']));
  assert.throws(() => parseArguments(['--not-an-option']));
  assert.throws(() => parseArguments(['--output']));
  const result = parseArguments(['--grid', '12x8', '--slides', '5,50']);
  assert.equal(result.mode, 'fidelity');
  assert.deepEqual(result.patch.selection, [5, 50]);
  assert.equal(result.patch.grid.columns, 12);
});
